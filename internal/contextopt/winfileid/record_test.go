package winfileid

import "testing"

// TestDecodeFileIDInfo checks the byte order and every byte copied from FILE_ID_INFO.
func TestDecodeFileIDInfo(t *testing.T) {
	record := Record{
		0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef,
		0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
		0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f,
	}
	wantID := [16]byte{
		0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
		0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f,
	}
	got := record.decode()
	if got.VolumeSerialNumber != 0xefcdab8967452301 || got.FileID != wantID {
		t.Fatalf("decoded volume %#016x, file ID %x", got.VolumeSerialNumber, got.FileID)
	}
}
